#!/usr/bin/env node

/**
 * Script to dynamically generate aws-exports.js from environment variables
 * This ensures the website always uses the correct AWS resource IDs from the deployed stack
 */

const fs = require('fs');
const path = require('path');

// Get environment variables with fallbacks
const region = process.env.REACT_APP_REGION || 'us-east-1';
const userPoolId = process.env.REACT_APP_USER_POOL_ID || 'us-east-1_M7IiQi3N5';
const userPoolClientId = process.env.REACT_APP_USER_POOL_CLIENT_ID || '4uql1ogjlnjvkj12crkq9eea33';
const identityPoolId = process.env.REACT_APP_IDENTITY_POOL_ID || 'us-east-1:ee2c71f8-a3e7-4768-bad1-c8dfdd8a6030';
const apiEndpoint = process.env.REACT_APP_API_BASE_URL || 'https://f2cf2rvu11.execute-api.us-east-1.amazonaws.com/v1';

// Log the values being used
console.log('Generating aws-exports.js with the following values:');
console.log(`  Region: ${region}`);
console.log(`  User Pool ID: ${userPoolId}`);
console.log(`  User Pool Client ID: ${userPoolClientId}`);
console.log(`  Identity Pool ID: ${identityPoolId}`);
console.log(`  API Endpoint: ${apiEndpoint}`);

// Create the aws-exports.js content
const awsExportsContent = `/* eslint-disable */
// WARNING: This file is automatically generated. Any changes will be overwritten.
// Generated on: ${new Date().toISOString()}

const awsmobile = {
  "aws_project_region": "${region}",
  "aws_cognito_identity_pool_id": "${identityPoolId}",
  "aws_cognito_region": "${region}",
  "aws_user_pools_id": "${userPoolId}",
  "aws_user_pools_web_client_id": "${userPoolClientId}",
  "oauth": {},
  "aws_cognito_username_attributes": ["email"],
  "aws_cognito_social_providers": [],
  "aws_cognito_signup_attributes": ["email"],
  "aws_cognito_mfa_configuration": "OFF",
  "aws_cognito_mfa_types": ["SMS"],
  "aws_cognito_password_protection_settings": {
    "passwordPolicyMinLength": 8,
    "passwordPolicyCharacters": []
  },
  "aws_cognito_verification_mechanisms": ["email"],
  "aws_appsync_graphqlEndpoint": "",
  "aws_appsync_region": "${region}",
  "aws_appsync_authenticationType": "API_KEY",
  "aws_appsync_apiKey": "",
  "aws_cloud_logic_custom": [
    {
      "name": "api",
      "endpoint": "${apiEndpoint}",
      "region": "${region}"
    }
  ]
};

export default awsmobile;
`;

// Write the file
const outputPath = path.join(__dirname, '..', 'src', 'aws-exports.js');
fs.writeFileSync(outputPath, awsExportsContent);

console.log(`✅ aws-exports.js has been generated at ${outputPath}`);
